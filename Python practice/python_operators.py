#  Arithmetic operators
x = 15
y = 4

print(x + y)
print(x - y)
print(x * y)
print(x / y)
print(x % y)
print(x ** y)
print(x // y)

# ========================================================================================
# Ternary operator
num = 6

x = "WEEKEND!" if num > 5 else "Workday"

print(x)

# =========================================================================================
# Comparision operator
x = 5
y = 3

print(x == y)
print(x != y)
print(x > y)
print(x < y)
print(x >= y)
print(x <= y)

# ======================================================================================================
# Logical operators
print(x > 0 and x < 10)
print(x < 5 or x > 10)
print(not(x > 3 and x < 10))